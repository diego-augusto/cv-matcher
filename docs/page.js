const english = {}; // filled from the markup the first time each element is translated

function setLang(lang) {
  if (!STRINGS[lang]) lang = "en";
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll("[data-i18n]")) {
    const key = el.dataset.i18n;
    english[key] ??= el.innerHTML;
    el.innerHTML = STRINGS[lang]?.[key] ?? english[key];
  }
  for (const button of document.querySelectorAll("[data-lang]")) button.setAttribute("aria-pressed", button.dataset.lang === lang);
}

for (const button of document.querySelectorAll("[data-lang]")) {
  button.addEventListener("click", () => {
    localStorage.setItem("cv-matcher-lang", button.dataset.lang);
    setLang(button.dataset.lang);
  });
}

// ?lang=pt wins (for links to one language), then the saved choice, then the browser language.
setLang(new URLSearchParams(location.search).get("lang") || localStorage.getItem("cv-matcher-lang") || navigator.language.slice(0, 2));
