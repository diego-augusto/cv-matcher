const LOCALES = { pt: "pt-BR", en: "en-US", es: "es" };
const currentLang = () => {
  const saved = localStorage.lang;
  if (saved in STRINGS) return saved;
  return Object.keys(STRINGS).find((code) => navigator.language.startsWith(code)) || "en";
};
const currentTheme = () => (["light", "dark"].includes(localStorage.theme) ? localStorage.theme : "system");
const locale = () => LOCALES[currentLang()];
const t = (key, vars = {}) => (STRINGS[currentLang()][key] ?? key).replace(/\{(\w+)\}/g, (_, name) => vars[name]);

// Applies theme and language to what is already in the DOM. Text built in JS calls t() when needed.
function applyPrefs() {
  const root = document.documentElement;
  root.lang = locale();
  root.dataset.theme = currentTheme();
  for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll("[data-i18n-placeholder]")) node.placeholder = t(node.dataset.i18nPlaceholder);
  for (const node of document.querySelectorAll("[data-i18n-aria-label]")) node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
}

applyPrefs(); // in <head>: sets the theme before first paint
document.addEventListener("DOMContentLoaded", applyPrefs);
addEventListener("storage", applyPrefs); // another extension page changed the preference
